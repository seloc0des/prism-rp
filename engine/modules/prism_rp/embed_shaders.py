"""Turns the Track B GLSL in addons/prism_rp/shaders into a C++ header, with every #include inlined.

The GDExtension loads the same files at runtime (load_and_preprocess_glsl in prism_rd_utils.cpp), so the
shaders exist once. Used by SCsub, and by tests/unit/test_embedded_shaders.py.
"""
from pathlib import Path

# Track B's passes. Chronos and Lumina stay in the GDExtension.
SHADER_DIRS = ("visibility", "shadows")


def resolve_includes(path: Path, include_dir: Path) -> str:
    """The source of path with each #include "x" replaced by x's own resolved source."""
    lines = []
    for line in path.read_text().splitlines():
        stripped = line.strip()
        if stripped.startswith("#extension GL_GOOGLE_include_directive"):
            continue
        if stripped.startswith("#include"):
            name = stripped.split('"')[1]
            local = path.parent / name
            lines.append(resolve_includes(local if local.exists() else include_dir / name, include_dir))
        else:
            lines.append(line)
    return "\n".join(lines)


def entry_points(shader_root: Path) -> list[Path]:
    return sorted(p for d in SHADER_DIRS for p in (shader_root / d).glob("*.glsl"))


def header_text(shader_root: Path) -> str:
    out = [
        "// Generated by engine/modules/prism_rp/embed_shaders.py. Do not edit.",
        "#pragma once",
        "",
        "struct PrismEmbeddedShader {",
        "\tconst char *name; // file name, for example vis_shade_materials.comp.glsl",
        "\tconst char *source; // GLSL with the includes inlined",
        "};",
        "",
        "static const PrismEmbeddedShader PRISM_EMBEDDED_SHADERS[] = {",
    ]
    for path in entry_points(shader_root):
        source = resolve_includes(path, shader_root / "include")
        assert ')PRISM_GLSL"' not in source
        out.append(f'\t{{ "{path.name}", R"PRISM_GLSL({source})PRISM_GLSL" }},')
    out += ["};", ""]
    return "\n".join(out)


def embed_shaders_builder(target, source, env):
    shader_root = Path(env["PRISM_SHADER_ROOT"])
    Path(str(target[0])).write_text(header_text(shader_root))
